# 포지션을 매개변수로 받아 챔피언 뽑아주는 함수 선언
def pick_champion(position):
    # 입력된 포지션에 맞는 키가 있다면?
    if position in champions:
        # 포지션 챔피언 리스트에서 하나 랜덤으로 뽑음
        return random.choice(champions[position])
    # 입력된 포지션에 맞는 키가 없다면
    return "올바른 포지션을 입력해주세요."


# 포지션 입력 받기 대문자 어퍼, 앞 뒤 공백 제거
position = input("포지션을 입력하세요: ").strip().upper()

print(pick_champion(position))
